// Generates shadcn-CLI-consumable registry JSON from src/registry/.
// Run: npm run registry:build
//
// Output lands in r/ — one registry-item file per component, plus an index.
// Nothing here is hand-maintained; edit the .tsx files and re-run.

import { readdir, readFile, writeFile, mkdir, rm } from "node:fs/promises";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const OUT = join(ROOT, "r");

// registry folder -> shadcn item type + where it lands in a consuming project
const FOLDERS = {
  ui: { type: "registry:ui", target: "components/ui" },
  blocks: { type: "registry:block", target: "components/blocks" },
  motion: { type: "registry:ui", target: "components/motion" },
};

// react/react-dom are peers of any consuming app — never list them as deps.
const PEERS = new Set(["react", "react-dom"]);

function parseImports(source) {
  const deps = new Set();
  const registryDeps = new Set();

  for (const match of source.matchAll(/from\s+["']([^"']+)["']/g)) {
    const spec = match[1];

    // "@/lib/utils" resolves in the consuming project, not here.
    if (spec === "@/lib/utils") continue;

    // a component importing a sibling primitive -> registry dependency
    const sibling = spec.match(/^@\/registry\/\w+\/(.+)$/);
    if (sibling) {
      registryDeps.add(sibling[1]);
      continue;
    }
    if (spec.startsWith("@/") || spec.startsWith(".")) continue;

    // scoped packages keep two segments, bare packages keep one
    const pkg = spec.startsWith("@")
      ? spec.split("/").slice(0, 2).join("/")
      : spec.split("/")[0];

    if (!PEERS.has(pkg)) deps.add(pkg);
  }

  return { deps: [...deps].sort(), registryDeps: [...registryDeps].sort() };
}

await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });

const index = [];

for (const [folder, { type, target }] of Object.entries(FOLDERS)) {
  const dir = join(ROOT, "src", "registry", folder);

  let entries = [];
  try {
    entries = await readdir(dir);
  } catch {
    continue; // folder not created yet
  }

  for (const file of entries.filter((f) => f.endsWith(".tsx"))) {
    const name = file.replace(/\.tsx$/, "");
    const path = `src/registry/${folder}/${file}`;
    const content = await readFile(join(dir, file), "utf8");
    const { deps, registryDeps } = parseImports(content);

    const item = {
      $schema: "https://ui.shadcn.com/schema/registry-item.json",
      name,
      type,
      dependencies: deps,
      registryDependencies: registryDeps,
      files: [{ path, content, type, target: `${target}/${file}` }],
    };

    await writeFile(join(OUT, `${name}.json`), JSON.stringify(item, null, 2) + "\n");
    index.push({ name, type, folder, dependencies: deps, registryDependencies: registryDeps });
  }
}

// The tokens every component above resolves against. A project that installs
// a component but not this gets unstyled output — bg-primary resolves to
// nothing. Ships as its own item so an existing project can skip it and keep
// the theme it already has.
const css = await readFile(join(ROOT, "src", "styles", "globals.css"), "utf8");

const vars = (block) =>
  Object.fromEntries([...block.matchAll(/--([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));

const rootBlock = css.match(/:root\s*\{([\s\S]*?)\n\}/);
// the bare @theme block — fonts and scale. The @theme *inline* block is skipped
// on purpose: it only maps names a consuming shadcn project already defines.
const themeBlock = css.match(/@theme\s*\{([\s\S]*?)\n\}/);

if (rootBlock) {
  const item = {
    $schema: "https://ui.shadcn.com/schema/registry-item.json",
    name: "theme",
    type: "registry:theme",
    cssVars: {
      ...(themeBlock ? { theme: vars(themeBlock[1]) } : {}),
      light: vars(rootBlock[1]),
    },
  };

  await writeFile(join(OUT, "theme.json"), JSON.stringify(item, null, 2) + "\n");
  index.push({ name: "theme", type: "registry:theme", folder: "styles", dependencies: [], registryDependencies: [] });
}

await writeFile(
  join(OUT, "registry.json"),
  JSON.stringify(
    {
      $schema: "https://ui.shadcn.com/schema/registry.json",
      name: "bass-ui",
      homepage: "https://github.com/bass/bass-ui",
      items: index.map(({ name, type }) => ({ name, type })),
    },
    null,
    2,
  ) + "\n",
);

// keep the plain tracking list in sync — it's the human-readable view
await writeFile(
  join(ROOT, "registry-index.json"),
  JSON.stringify(
    {
      note: "Generated by scripts/build-registry.mjs — do not hand-edit. CLI-consumable output lives in r/.",
      components: index.sort((a, b) => a.name.localeCompare(b.name)),
    },
    null,
    2,
  ) + "\n",
);

console.log(`built ${index.length} registry items -> r/`);
for (const i of index) console.log(`  ${i.folder}/${i.name}`);
